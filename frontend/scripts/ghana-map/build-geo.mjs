/**
 * Builds src/components/home/ghana-map/geo.ts: the home page's map of Ghana
 * as ready-drawn SVG paths, so the page ships no map library and no
 * projection maths for the country itself.
 *
 * Sources:
 *   - The 16 regions: @amcharts/amcharts5-geodata (json/ghanaHigh.json),
 *     under the free amCharts licence (LICENSE-amcharts.txt beside geo.ts),
 *     which is why the map carries a "Map data: amCharts" credit.
 *   - Lake Volta and the rivers: Natural Earth 1:50m (public domain), via
 *     sane-topojson (dist/africa_50m.json).
 *
 * To rebuild, in an empty folder:
 *   npm i @amcharts/amcharts5-geodata@5.2.0 sane-topojson@4.0.0 topojson-client@3.1.0
 *   node <this file> > <repo>/frontend/src/components/home/ghana-map/geo.ts
 */
import fs from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(`${process.cwd()}/`);
const { feature } = require("topojson-client");
const read = (name) => JSON.parse(fs.readFileSync(require.resolve(name)));

// Keep in step with BOUNDS and WIDTH in ../../src/components/home/ghana-map/project.ts.
const B = { s: 4.62, n: 11.22, w: -3.3, e: 1.25 };
const W = 600;
const PAD = 14;
const K = (W - 2 * PAD) / (B.e - B.w);
const H = Math.round((B.n - B.s) * K + 2 * PAD);
const P = (lat, lng) => [PAD + (lng - B.w) * K, PAD + (B.n - lat) * K];

function dp(pts, eps) {
  if (pts.length < 3) return pts;
  let dmax = 0, idx = 0;
  const [x1, y1] = pts[0], [x2, y2] = pts[pts.length - 1];
  const L = Math.hypot(y2 - y1, x2 - x1);
  for (let i = 1; i < pts.length - 1; i++) {
    const [x, y] = pts[i];
    const d = L < 1e-9 ? Math.hypot(x - x1, y - y1) : Math.abs((y2 - y1) * x - (x2 - x1) * y + x2 * y1 - y2 * x1) / L;
    if (d > dmax) { dmax = d; idx = i; }
  }
  if (dmax > eps) return dp(pts.slice(0, idx + 1), eps).slice(0, -1).concat(dp(pts.slice(idx), eps));
  return [pts[0], pts[pts.length - 1]];
}
const ring = (r, eps) => { const m = Math.floor(r.length / 2); return dp(r.slice(0, m + 1), eps).slice(0, -1).concat(dp(r.slice(m), eps).slice(0, -1)); };
const xy = ([lng, lat]) => P(lat, lng).map((v) => v.toFixed(1)).join(",");
const closed = (r) => `M${r.map(xy).join("L")}Z`;
const open = (r) => `M${r.map(xy).join("L")}`;
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-");

// Where each region's name sits, when the middle of its outline is a poor place.
const LABEL_AT = {
  "Greater Accra": [5.3, -0.02], Central: [5.62, -1.25], Western: [5.45, -2.35], "Western North": [6.45, -2.78],
  Ahafo: [7.02, -2.48], Bono: [7.8, -2.6], Volta: [6.3, 0.66], Eastern: [6.55, -0.6], Ashanti: [6.98, -1.3],
  Oti: [8.35, 0.4], "Upper West": [10.4, -2.3], "Upper East": [10.98, -0.55], "North East": [10.42, -0.1],
  Northern: [9.6, -0.35], Savannah: [9.25, -1.6], "Bono East": [7.95, -1.25],
};

const am = read("@amcharts/amcharts5-geodata/json/ghanaHigh.json");
const regions = am.features.map((f) => {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  const d = polys.map((p) => ring(p[0], 0.008)).filter((r) => r.length > 3).map(closed).join("");
  const [lat, lng] = LABEL_AT[f.properties.name];
  const [x, y] = P(lat, lng);
  return { name: f.properties.name, slug: slug(f.properties.name), d, label: [+x.toFixed(1), +y.toFixed(1)] };
}).sort((a, b) => a.name.localeCompare(b.name));

const ne = read("sane-topojson/dist/africa_50m.json");
const near = ([x, y]) => x > B.w - 0.3 && x < B.e + 0.3 && y > B.s - 0.3 && y < B.n + 0.3;
const lines = (object, eps, isArea) => feature(ne, ne.objects[object]).features.flatMap((f) => {
  const g = f.geometry;
  if (!g) return [];
  const parts = g.type.startsWith("Multi") ? g.coordinates : [g.coordinates];
  return parts.map((p) => (isArea ? p[0] : p)).filter((p) => p.some(near))
    .map((p) => (isArea ? closed(ring(p, eps)) : open(dp(p, eps))));
});

const out = {
  width: W, height: H,
  regions,
  lakes: lines("lakes", 0.006, true),
  rivers: lines("rivers", 0.01, false),
};

process.stdout.write(`/* Generated by frontend/scripts/ghana-map/build-geo.mjs. Do not edit by hand.
   Regions: amCharts geodata (see LICENSE-amcharts.txt). Water: Natural Earth (public domain). */

export type MapRegion = { name: string; slug: string; d: string; label: [number, number] };

export const GEO: {
  width: number;
  height: number;
  regions: MapRegion[];
  lakes: string[];
  rivers: string[];
} = ${JSON.stringify(out)};
`);
